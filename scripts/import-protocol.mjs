// Writes docs/protocol.md: a sanitized copy of the protocol specification whose original source is the GE150PRO
// research repository (klaushofrichter/GE150PRO, private: docs/protocol/README.md). Kept: the specification, its
// evidence labels and the open questions. Left out: how the research was done on the owner's machine (traffic capture
// by injection into Mooer's editor, local paths, the webcam set-up, the research repository's tests) and where the
// firmware files are kept. Re-run after the original changes:
//   node scripts/import-protocol.mjs ../GE150PRO/docs/protocol/README.md
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/import-protocol.mjs <GE150PRO>/docs/protocol/README.md");
let md = readFileSync(src, "utf8");

const section = (title) => {
  const at = md.indexOf(`\n## ${title}`);
  if (at < 0) throw new Error(`section not found: ${title}`);
  const next = md.indexOf("\n## ", at + 4);
  return [at, next < 0 ? md.length : next];
};

// Everything from Methods on is about the research set-up.
md = md.slice(0, section("Methods")[0]) + "\n";
// The firmware section: keep the analysis, drop where the images are kept and their hashes.
{
  const [a, b] = section("Firmware analysis");
  let s = md.slice(a, b);
  s = s.replace(/\nThe official editor ships the firmware[\s\S]*?\n\n/, "\n");
  md = md.slice(0, a) + s + md.slice(b);
}
const replacements = [
  [/Reproducible from `captures\/raw\/session\*\.log` \(local only, not committed\)\./g, "From captures of the official editor's traffic in the GE150PRO repository."],
  [/captures\/raw\/session\d\.log/g, "a capture"],
  [/`captures\/raw\/[^`]*`/g, "captures"],
  [/with the owner's go-ahead/g, "with the pedal owner's consent"],
  [/\(session \d+[,:)]/g, "("],
  [/\(session \d+\)/g, ""],
  [/session \d+: /g, ""],
  [/ of session \d+/g, " captured from the editor"],
  [/Keep them accurate when you edit this file\./g, "The original keeps them up to date."],
  [/ names the cheapest method from \[Methods\]\(#methods\)/g, " names the cheapest method (described in the original)"],
];
for (const [re, to] of replacements) md = md.replace(re, to);

const intro = `<!-- Generated by scripts/import-protocol.mjs. Do not edit here: change the original and import again. -->

> **Sanitized copy.** The original source of this specification is the GE150PRO research repository
> (\`klaushofrichter/GE150PRO\`, \`docs/protocol/README.md\`), where every claim is traced to captures, static analysis
> or tests on the pedal. This copy keeps the specification and the open questions and leaves out how the research was
> done. Unofficial: not affiliated with or endorsed by Mooer.

`;
const firstHeading = md.indexOf("\n## ");
const title = md.slice(0, md.indexOf("\n")).trim();
md = `${title}\n\n${intro}${md.slice(firstHeading + 1)}`;
md += `## Safety

The game sends only commands observed from Mooer's editor. It never sends factory reset, firmware, \`8B\` or \`BA\`
(they erase flash), never tries unknown command bytes or arguments (\`B4 15\` opens the reset prompt), and asks before
writing a preset slot (\`C3\`).
`;
writeFileSync(new URL("../docs/protocol.md", import.meta.url), md.replace(/\n{3,}/g, "\n\n"));
console.log("docs/protocol.md written");
